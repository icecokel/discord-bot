#!/usr/bin/env node
/**
 * Builds the production .env from GitHub Actions secrets and variables.
 *
 * Usage (in the deploy workflow):
 *   BOT_SECRETS_JSON='{"NAME": ${{ toJSON(secrets.NAME) }}, ...}' BOT_VARS_JSON='${{ toJSON(vars) }}' \
 *     node scripts/render-production-env.cjs <output-file>
 *
 * Secrets are listed one by one in the workflow: passing toJSON(secrets) wholesale into a script
 * on a self-hosted runner looks like exfiltration and GitHub holds such runs for approval.
 *
 * - Every listed secret and every repository variable becomes one KEY=value line; empty or
 *   unset ones are skipped (the workflow lists secrets explicitly, so optional ones may be unset).
 * - GitHub forbids names starting with GITHUB_, so a GH_ prefix is written as GITHUB_
 *   (GH_TOKEN -> GITHUB_TOKEN, GH_ACTIONS_MONITOR_REPO -> GITHUB_ACTIONS_MONITOR_REPO).
 * - With no bot settings at all, nothing is written and the server keeps its current .env.
 * - Names are printed; values never are.
 */
const fs = require("node:fs");
const path = require("node:path");

const REQUIRED = ["DISCORD_BOT_TOKEN", "ADMIN_ID"];
// Provided by GitHub itself, not part of the bot configuration.
const IGNORED = new Set(["github_token", "GITHUB_TOKEN"]);
const NAME_PATTERN = /^[A-Z][A-Z0-9_]*$/;

const parseContext = (raw, label) => {
  if (!raw || !raw.trim()) return {};
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error(`${label} is not valid JSON.`);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error(`${label} must be a JSON object.`);
  return parsed;
};

const toEnvName = (name) => (name.startsWith("GH_") ? `GITHUB_${name.slice(3)}` : name);

/** dotenv-compatible quoting: single quotes keep the value literal; double quotes carry newlines. */
const formatValue = (name, value) => {
  const text = String(value).replace(/\r\n/g, "\n");
  if (!text.includes("\n") && !text.includes("'")) return `'${text}'`;
  if (!text.includes('"')) return `"${text.replace(/\n/g, "\\n")}"`;
  throw new Error(`${name} contains both quotes and newlines/single quotes; it cannot be written to .env safely.`);
};

const render = (secrets, vars) => {
  const entries = new Map();
  const sources = { secret: [], variable: [] };
  for (const [kind, context] of [["secret", secrets], ["variable", vars]]) {
    for (const [rawName, value] of Object.entries(context)) {
      if (IGNORED.has(rawName) || value === null || value === undefined || String(value) === "") continue;
      if (!NAME_PATTERN.test(rawName)) throw new Error(`Unsupported name "${rawName}": use upper-case letters, digits and _.`);
      const name = toEnvName(rawName);
      if (entries.has(name)) throw new Error(`${name} is defined more than once (secret and variable, or GH_ and plain name).`);
      entries.set(name, value);
      sources[kind].push(name);
    }
  }
  return { entries, sources };
};

const main = () => {
  const output = process.argv[2];
  if (!output) throw new Error("Usage: render-production-env.cjs <output-file>");
  const { entries, sources } = render(
    parseContext(process.env.BOT_SECRETS_JSON, "BOT_SECRETS_JSON"),
    parseContext(process.env.BOT_VARS_JSON, "BOT_VARS_JSON"),
  );

  if (entries.size === 0) {
    console.log("No bot settings in GitHub secrets/variables; the server keeps its current .env.");
    return;
  }
  const missing = REQUIRED.filter((name) => !String(entries.get(name) ?? "").trim());
  if (missing.length) {
    throw new Error(`Missing required settings: ${missing.join(", ")}. Nothing was changed on the server.`);
  }

  const lines = [
    "# Generated by the deploy workflow from GitHub secrets and variables. Do not edit on the server.",
    ...[...entries.keys()].sort().map((name) => `${name}=${formatValue(name, entries.get(name))}`),
    "",
  ];
  fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
  fs.writeFileSync(output, lines.join("\n"), { mode: 0o600 });
  fs.chmodSync(output, 0o600);
  console.log(`Rendered ${entries.size} settings.`);
  console.log(`  secrets:   ${sources.secret.sort().join(", ") || "-"}`);
  console.log(`  variables: ${sources.variable.sort().join(", ") || "-"}`);
};

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(`render-production-env: ${error.message}`);
    process.exit(1);
  }
}

module.exports = { render, formatValue, toEnvName };
